"""AI foundation interfaces for layout reasoning and decision support."""

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.models.problem import FacilityLayoutProblem
from app.models.solution import LayoutSolution
from app.evaluation.engine import EvaluationReport


class LayoutSuggestion(BaseModel):
    """Actionable improvement recommendation proposed by an AI assistant."""

    category: str = Field(..., description="e.g. 'department_swap', 'aisle_widening', 'hazard_isolation'")
    title: str = Field(..., description="Short summary of suggestion")
    rationale: str = Field(..., description="Engineering reasoning behind the change")
    suggested_actions: List[str] = Field(default_factory=list)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)


class LayoutDiagnosis(BaseModel):
    """Comprehensive diagnosis of a layout candidate generated by AI."""

    layout_id: str
    strengths: List[str] = Field(default_factory=list)
    weaknesses: List[str] = Field(default_factory=list)
    suggestions: List[LayoutSuggestion] = Field(default_factory=list)
    executive_summary: str = Field(default="")


class BaseLayoutAdvisor(ABC):
    """Abstract interface for AI layout advisor (e.g. powered by Gemini API)."""

    @property
    @abstractmethod
    def model_name(self) -> str:
        pass

    @abstractmethod
    async def diagnose_layout(
        self,
        problem: FacilityLayoutProblem,
        solution: LayoutSolution,
        evaluation: EvaluationReport,
    ) -> LayoutDiagnosis:
        """Provide automated industrial engineering feedback on a layout."""
        pass
